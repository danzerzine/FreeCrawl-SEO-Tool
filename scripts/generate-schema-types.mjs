#!/usr/bin/env node
/**
 * Regenerates `packages/core/src/schema-types.ts`: for every schema.org type
 * under one of the names the structured-data rules care about, which of those
 * names it descends from. `schema-rules.ts` uses it so a rule written for
 * `LocalBusiness` also checks `Restaurant`, and an exclusion such as
 * `BroadcastEvent` also covers its subtypes.
 *
 * Read from the schema.org vocabulary release file once, here, so the crawler
 * never fetches it. Re-run after adding a rule root or exclusion to
 * `schema-rules.ts`, or after a schema.org release:
 *   node scripts/generate-schema-types.mjs [path-to-schemaorg-current-https.jsonld]
 *
 * Without a path the file is fetched from schema.org. The header of the
 * generated file names the source (URL or file name), its sha256 and the day
 * it was read, so a run on a saved copy can be checked against the original.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { basename, dirname, join } from 'node:path';

const SOURCE = 'https://schema.org/version/latest/schemaorg-current-https.jsonld';
/** Every rule root and every exclusion named in `schema-rules.ts`. */
const NAMES = [
  'AggregateOffer',
  'AggregateRating',
  'Answer',
  'Article',
  'BlogPosting',
  'BreadcrumbList',
  'BroadcastEvent',
  'ClaimReview',
  'Clip',
  'Comment',
  'Course',
  'CourseInstance',
  'DataFeed',
  'Dataset',
  'DefinedRegion',
  'DeliveryEvent',
  'DiscussionForumPosting',
  'EmployerAggregateRating',
  'Event',
  'EventSeries',
  'FAQPage',
  'HowTo',
  'HowToDirection',
  'HowToSection',
  'HowToStep',
  'HowToTip',
  'ImageObject',
  'InteractionCounter',
  'ItemList',
  'JobPosting',
  'ListItem',
  'LocalBusiness',
  'MathSolver',
  'MemberProgram',
  'MemberProgramTier',
  'MerchantReturnPolicy',
  'Movie',
  'Offer',
  'OfferShippingDetails',
  'OperatingSystem',
  'Organization',
  'Product',
  'ProductGroup',
  'ProfilePage',
  'PublicationEvent',
  'QAPage',
  'Question',
  'Quiz',
  'Recipe',
  'Recommendation',
  'Restaurant',
  'Review',
  'ReviewNewsArticle',
  'RuntimePlatform',
  'SeekToAction',
  'ShippingService',
  'SocialMediaPosting',
  'SoftwareApplication',
  'SpeakableSpecification',
  'UnitPriceSpecification',
  'VideoGame',
  'VideoObject',
  'WebSite',
];

const inputPath = process.argv[2];
const raw = inputPath ? readFileSync(inputPath, 'utf8') : await (await fetch(SOURCE)).text();
const sourceName = inputPath ? basename(inputPath) : SOURCE;
const sha256 = createHash('sha256').update(raw).digest('hex');
const graph = JSON.parse(raw)['@graph'];
const strip = (id) => id.replace(/^schema:/, '');
const parents = new Map();
for (const node of graph) {
  const types = [node['@type']].flat();
  if (!types.includes('rdfs:Class')) continue;
  const sup = node['rdfs:subClassOf'];
  parents.set(strip(node['@id']), sup ? [sup].flat().map((s) => strip(s['@id'])) : []);
}
for (const name of NAMES) if (!parents.has(name)) throw new Error(`not a schema.org type: ${name}`);

const ancestors = (type) => {
  const seen = new Set();
  const walk = (t) => {
    for (const p of parents.get(t) ?? []) {
      if (seen.has(p)) continue;
      seen.add(p);
      walk(p);
    }
  };
  walk(type);
  return seen;
};
const wanted = new Set(NAMES);
const lines = [];
for (const type of [...parents.keys()].sort()) {
  const hits = [...ancestors(type)].filter((a) => wanted.has(a)).sort();
  if (hits.length > 0 || wanted.has(type)) lines.push(`  ${type}: '${hits.join(' ')}',`);
}

const out = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'packages',
  'core',
  'src',
  'schema-types.ts',
);
writeFileSync(
  out,
  `// Generated by scripts/generate-schema-types.mjs from ${sourceName}` +
    ` (sha256 ${sha256}, read ${new Date().toISOString().slice(0, 10)}). Do not edit by hand — re-run the script.\n\n` +
    `/**\n * schema.org types under the names the structured-data rules use, each with\n` +
    ` * the space-separated list of those names it descends from (empty for a\n * listed name with none above it).\n */\n` +
    `export const SCHEMA_ANCESTORS: Readonly<Record<string, string>> = {\n${lines.join('\n')}\n};\n`,
);
console.log(`schema-types.ts: ${lines.length} types`);
