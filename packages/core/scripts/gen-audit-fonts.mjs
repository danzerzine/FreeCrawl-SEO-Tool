// Regenerates packages/core/src/audit-report/fonts.generated.ts from the woff2 files in
// packages/core/assets/audit-fonts (Literata 600, Golos Text 400/500/600; latin and cyrillic
// subsets of the @fontsource 5.3.0 builds; SIL Open Font License 1.1, texts next to the files).
// The latin files are patched by scripts/patch-audit-fonts.py (U+202F glyph).
// The audit report embeds them as data: URLs so the page makes no network request.
// Run: node packages/core/scripts/gen-audit-fonts.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const dir = new URL('../assets/audit-fonts/', import.meta.url);
const out = new URL('../src/audit-report/fonts.generated.ts', import.meta.url);
const LATIN =
  'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD';
const CYRILLIC = 'U+0301,U+0400-045F,U+0490-0491,U+04B0-04B1,U+2116';
const faces = [];
for (const [family, stem, weights] of [
  ['Literata', 'literata', [600]],
  ['Golos Text', 'golos-text', [400, 500, 600]],
]) {
  for (const weight of weights) {
    for (const [subset, range] of [
      ['latin', LATIN],
      ['cyrillic', CYRILLIC],
    ]) {
      const file = `${stem}-${subset}-${weight}-normal.woff2`;
      faces.push({
        family,
        weight,
        range,
        file,
        data: readFileSync(new URL(file, dir)).toString('base64'),
      });
    }
  }
}
const body = faces
  .map(
    (f) =>
      `  {\n    family: '${f.family}',\n    weight: ${f.weight},\n    unicodeRange: '${f.range}',\n    file: '${f.file}',\n    woff2Base64:\n      '${f.data}',\n  },`,
  )
  .join('\n');
writeFileSync(
  fileURLToPath(out),
  `// Generated by packages/core/scripts/gen-audit-fonts.mjs from packages/core/assets/audit-fonts; do not edit.
// Literata: Copyright 2017 The Literata Project Authors (https://github.com/googlefonts/literata).
// Golos Text: Copyright 2019 The Golos Text Project Authors (https://github.com/googlefonts/golos-text).
// Both under the SIL Open Font License 1.1 (assets/audit-fonts/*-OFL.txt).

export interface EmbeddedFontFace {
  family: string;
  weight: number;
  unicodeRange: string;
  /** Source file in assets/audit-fonts. */
  file: string;
  woff2Base64: string;
}

export const AUDIT_FONT_FACES: readonly EmbeddedFontFace[] = [
${body}
];
`,
);
console.log(`wrote ${faces.length} faces`);
